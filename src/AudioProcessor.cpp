#pragma once

#include <Arduino.h>
#include <array>
#include <Preferences.h>

class AudioProcessor {
public:
  static constexpr size_t kEqBandCount = 10;

  AudioProcessor();

  void begin();
  void resetDefaults();
  bool saveSettings();
  bool loadSettings();

  void setMasterGain(float dB);
  void setChannelGain(float lowDb, float midDb, float highDb);
  void setEqBand(size_t index, float dB);
  void setCrossover(float lowMidHz, float midHighHz);
  float processSample(float input);
  void printStatus() const;
  float getBandFrequency(size_t index) const;

private:
  struct EqBandState {
    float lowpass;
    float highpass;
    float lastSample;
  };

  struct Config {
    float masterGainDb;
    float channelLowDb;
    float channelMidDb;
    float channelHighDb;
    float eqGainDb[kEqBandCount];
    float crossoverLowMidHz;
    float crossoverMidHighHz;
  };

  Config config_;
  std::array<EqBandState, kEqBandCount> eqStates_;
  float lowFilterState_;
  float midFilterState_;
  float highFilterState_;
  Preferences prefs_;

  float dbToGain(float dB) const;
  float applyBand(float input, size_t bandIndex, float gainDb);
  float lowPass(float input, float cutoffHz, float sampleRate, float &state);
  float highPass(float input, float cutoffHz, float sampleRate, float &state);
  float processLowBand(float input);
  float processMidBand(float input);
  float processHighBand(float input);
};







































































































































































































































































































































































































































































































































































































































































































































